"""Run one model, at any package version, on UCR datasets in a throwaway environment.

The script builds a temporary venv with .venv's Python and pinned packages, installs --package
on top (a TSCGlue branch/commit, an aeon version, ...), runs every (dataset, resample) as its own
process in that venv, writes tsml results locally, and deletes the venv at the end.

    # TSCGlue at a branch (resolved to a commit), 50 smallest UCR datasets, resamples 0-9
    uv run --no-sync python scripts/run_model.py \\
        --package git+https://github.com/gasperpetelin/TSCGlue@feat/blend-head \\
        --estimator tscglue.models:TSCGlueEnhancedV4 -p preset=best -p eval_metric=log_loss \\
        --smallest 50 -r 0-9 --cpus 8 --gpu --parallel 4

    # an aeon model at a given aeon version, two datasets
    uv run --no-sync python scripts/run_model.py --package aeon==1.3.0 \\
        --estimator aeon.classification.convolution_based:MultiRocketHydraClassifier \\
        -d Beef,Rock -r 0-4 --cpus 8

Results: <output-dir>/<name>/Predictions/<dataset>/testResample<k>.csv, one log per job in
<output-dir>/<name>/logs/. Existing results are skipped unless --overwrite. The estimator gets
random_state=<resample>, n_jobs=--cpus, n_gpus=1/0 and runs_dir=<temp dir> when its __init__
takes them. Parameter values are Python literals (True, 10, 0.5, "x"); anything else is a string.
"""

import argparse
import ast
import hashlib
import importlib
import inspect
import os
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MAIN_PYTHON = PROJECT_ROOT / ".venv" / "bin" / "python"
TORCH_INDEX = "https://download.pytorch.org/whl/cu132"


# ----------------------------- inside the job's venv -----------------------------

def parse_params(pairs):
    params = {}
    for pair in pairs:
        key, sep, value = pair.partition("=")
        if not sep:
            raise SystemExit(f"parameter {pair!r} is not key=value")
        try:
            params[key] = ast.literal_eval(value)
        except (ValueError, SyntaxError):
            params[key] = value
    return params


def run_job(args):
    """One (dataset, resample): fit, predict and write the tsml TEST results file.

    Only aeon's .ts loader and tsml-eval's results writer (numpy only) are used, so this works
    with whatever aeon version the package under test brings.
    """
    import time
    from datetime import datetime

    import numpy as np
    from aeon.datasets import load_from_ts_file
    from tsml_eval.utils.results_writing import write_classification_results

    # aeon's zero-variance guard false-positives valid fits (see run_benchmark2.py): warn instead.
    try:
        import aeon.base._base_collection as base_collection

        original = base_collection.check_collection_variance
        base_collection.check_collection_variance = (
            lambda X, threshold=1e-7, raise_error=True: original(X, threshold=threshold, raise_error=False))
    except (ImportError, AttributeError):
        pass

    module, _, cls_name = args.estimator.partition(":")
    cls = getattr(importlib.import_module(module), cls_name)
    folder = Path(args.data_dir) / args.dataset
    X_train, y_train = load_from_ts_file(str(folder / f"{args.dataset}{args.resample}_TRAIN.ts"))
    X_test, y_test = load_from_ts_file(str(folder / f"{args.dataset}{args.resample}_TEST.ts"))
    labels = np.unique(y_train)  # the same encoding as tsml-eval's LabelEncoder
    y_train, y_test = np.searchsorted(labels, y_train), np.searchsorted(labels, y_test)

    with tempfile.TemporaryDirectory() as run_dir:
        accepted = inspect.signature(cls.__init__).parameters
        defaults = {"random_state": args.resample, "n_jobs": args.cpus,
                    "n_gpus": 1 if args.gpu else 0, "runs_dir": run_dir}
        params = {k: v for k, v in defaults.items() if k in accepted} | parse_params(args.param)
        print(f"{args.name} {args.dataset} resample={args.resample} {cls.__module__}.{cls_name}({params})",
              flush=True)
        clf = cls(**params)
        start = time.time()
        clf.fit(X_train, y_train)
        fit_ms = int((time.time() - start) * 1000)
        start = time.time()
        probs = clf.predict_proba(X_test)
        predict_ms = int((time.time() - start) * 1000)

    preds = np.asarray(clf.classes_)[np.argmax(probs, axis=1)]
    write_classification_results(
        preds, probs, y_test, args.name, args.dataset, args.output_dir, full_path=False,
        first_line_classifier_name=f"{args.name} ({cls_name})", split="TEST",
        resample_id=args.resample, time_unit="MILLISECONDS",
        first_line_comment=(f"Generated by run_model.py on {datetime.now():%m/%d/%Y, %H:%M:%S}. "
                            f"Encoder dictionary: { {str(c): i for i, c in enumerate(labels)} }."),
        parameter_info=str(params).replace("\n", " "), accuracy=float((preds == y_test).mean()),
        fit_time=fit_ms, predict_time=predict_ms, n_classes=len(labels),
    )
    print(f"fit {fit_ms / 1000:.1f}s, predict {predict_ms / 1000:.1f}s, "
          f"accuracy {(preds == y_test).mean():.4f}", flush=True)


# ----------------------------- driver (outside the venv) -----------------------------

def parse_resamples(text):
    out = []
    for part in text.split(","):
        lo, _, hi = part.strip().partition("-")
        out.extend(range(int(lo), int(hi) + 1) if hi else [int(lo)])
    return sorted(set(out))


def n_train(dataset, data_dir):
    with open(Path(data_dir) / dataset / f"{dataset}0_TRAIN.ts") as f:
        for line in f:
            if line.strip().lower() == "@data":
                break
        return sum(1 for line in f if line.strip())


def resolve_package(package):
    """git+URL@<branch|tag> -> git+URL@<full commit>; anything else unchanged. Returns (spec, label)."""
    m = re.fullmatch(r"git\+(?P<url>[^@]+)@(?P<ref>.+)", package)
    if not m:
        return package, re.sub(r"[^A-Za-z0-9.]+", "", package.split("=")[-1]) or package
    url, ref = m["url"], m["ref"]
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        sha = ref
    else:
        out = subprocess.run(["git", "ls-remote", url, ref, f"{ref}^{{}}"], check=True,
                             capture_output=True, text=True).stdout.split()
        shas = [s for s in out[::2]]
        if not shas and re.fullmatch(r"[0-9a-f]{7,39}", ref):
            sha = ref  # short commit: uv resolves it
        elif not shas:
            raise SystemExit(f"{url} has no ref {ref!r}")
        else:
            sha = shas[-1]  # the peeled commit of an annotated tag comes last
    return f"git+{url}@{sha}", sha[:7]


def build_env(env_dir, package, extra):
    """venv with .venv's Python and exact package versions, then `package` (and extras) on top."""
    version = subprocess.run([str(MAIN_PYTHON), "-c", "import platform; print(platform.python_version())"],
                             check=True, capture_output=True, text=True).stdout.strip()
    subprocess.run(["uv", "venv", "-q", "--python", version, str(env_dir)], check=True)
    python = str(env_dir / "bin" / "python")
    freeze = subprocess.run(["uv", "pip", "freeze", "--python", str(MAIN_PYTHON)],
                            check=True, capture_output=True, text=True).stdout.splitlines()
    # .venv's versions minus tscglue and this project; the package under test replaces them.
    reqs = [line for line in freeze if not line.startswith(("tscglue", "-e ", "tscbench"))]
    req_file = env_dir / "base-requirements.txt"
    req_file.write_text("\n".join(reqs) + "\n")
    # --no-deps: .venv's freeze is not a consistent resolution (e.g. fsspec vs datasets).
    subprocess.run(["uv", "pip", "install", "-q", "--python", python, "--no-deps", "-r", str(req_file),
                    "--extra-index-url", TORCH_INDEX, "--index-strategy", "unsafe-best-match"], check=True)
    subprocess.run(["uv", "pip", "install", "-q", "--python", python, "--no-deps", package, *extra],
                   check=True)
    return python


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--package", required=True,
                    help="git+URL@<branch|tag|commit> or a pip spec, e.g. aeon==1.3.0")
    ap.add_argument("--estimator", required=True, help="module:Class, e.g. tscglue.models:TSCGlueEnhancedV4")
    ap.add_argument("-p", "--param", action="append", default=[], help="key=value, repeatable")
    ap.add_argument("--name", help="classifier name in the results (default: Class-<commit|version>-<hash>)")
    data = ap.add_mutually_exclusive_group(required=True)
    data.add_argument("-d", "--datasets", help="comma-separated dataset names")
    data.add_argument("--smallest", type=int, help="the N UCR equal-length datasets with fewest training cases")
    data.add_argument("--all", action="store_true", help="all 112 UCR equal-length datasets")
    ap.add_argument("-r", "--resamples", default="0-9", help="e.g. 0-9 or 0,3,5 (default 0-9)")
    ap.add_argument("--cpus", type=int, default=8, help="n_jobs per job (default 8)")
    ap.add_argument("--gpu", action="store_true", help="give each job GPU 0 (n_gpus=1)")
    ap.add_argument("--parallel", type=int, default=1, help="jobs run at the same time (default 1)")
    ap.add_argument("--with", dest="extra", action="append", default=[],
                    help="extra package installed into the venv, repeatable")
    ap.add_argument("-o", "--output-dir", default=str(PROJECT_ROOT / "model_runs"))
    ap.add_argument("--data-dir", default=str(PROJECT_ROOT / "data"))
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--keep-env", action="store_true", help="do not delete the venv at the end")
    args = ap.parse_args()

    package, label = resolve_package(args.package)
    cls_name = args.estimator.rpartition(":")[2]
    params_hash = hashlib.sha256(" ".join(sorted(args.param)).encode()).hexdigest()[:6]
    name = args.name or f"{cls_name}-{label}-{params_hash}"
    if args.datasets:
        datasets = [d.strip() for d in args.datasets.split(",") if d.strip()]
    else:
        from aeon.datasets.tsc_datasets import univariate_equal_length

        datasets = sorted(univariate_equal_length, key=lambda d: (n_train(d, args.data_dir), d))
        datasets = datasets if args.all else datasets[:args.smallest]
    resamples = parse_resamples(args.resamples)
    results = Path(args.output_dir) / name
    jobs = [(d, r) for d in datasets for r in resamples
            if args.overwrite or not (results / "Predictions" / d / f"testResample{r}.csv").exists()]
    print(f"{name}: {package} {args.estimator} {args.param}")
    print(f"{len(jobs)} of {len(datasets) * len(resamples)} jobs to run, results in {results}", flush=True)
    if not jobs:
        return

    env_dir = Path(tempfile.mkdtemp(prefix="run-model-env-"))
    try:
        print(f"building venv in {env_dir}", flush=True)
        python = build_env(env_dir, package, args.extra)
        (results / "logs").mkdir(parents=True, exist_ok=True)
        job_env = os.environ | {"CUDA_VISIBLE_DEVICES": "0" if args.gpu else "", "HF_HUB_OFFLINE": "1",
                                "OMP_NUM_THREADS": "1", "MKL_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1"}

        def run(job):
            dataset, resample = job
            cmd = [python, str(Path(__file__).resolve()), "_job", "--estimator", args.estimator,
                   "--name", name, "--dataset", dataset, "--resample", str(resample),
                   "--cpus", str(args.cpus), "--output-dir", args.output_dir, "--data-dir", args.data_dir,
                   *[x for p in args.param for x in ("-p", p)],
                   *(["--gpu"] if args.gpu else []), *(["--overwrite"] if args.overwrite else [])]
            with open(results / "logs" / f"{dataset}_{resample}.log", "w") as log:
                code = subprocess.run(cmd, env=job_env, stdout=log, stderr=subprocess.STDOUT).returncode
            print(f"{'ok  ' if code == 0 else 'FAIL'} {dataset} resample={resample}", flush=True)
            return code == 0

        with ThreadPoolExecutor(args.parallel) as pool:
            ok = list(pool.map(run, jobs))
        print(f"done: {sum(ok)} ok, {len(ok) - sum(ok)} failed (see {results / 'logs'})")
        sys.exit(0 if all(ok) else 1)
    finally:
        if args.keep_env:
            print(f"kept venv {env_dir}")
        else:
            shutil.rmtree(env_dir, ignore_errors=True)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "_job":
        jp = argparse.ArgumentParser()
        for flag in ("--estimator", "--name", "--dataset", "--output-dir", "--data-dir"):
            jp.add_argument(flag, required=True)
        jp.add_argument("--resample", type=int, required=True)
        jp.add_argument("--cpus", type=int, required=True)
        jp.add_argument("-p", "--param", action="append", default=[])
        jp.add_argument("--gpu", action="store_true")
        jp.add_argument("--overwrite", action="store_true")
        run_job(jp.parse_args(sys.argv[2:]))
    else:
        main()
